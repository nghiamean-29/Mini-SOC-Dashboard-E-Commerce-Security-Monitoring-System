-- =============================================================================
-- V5 : SECURITY EVENTS  (the raw facts of the SOC - the largest table)
-- -----------------------------------------------------------------------------
-- This table is the raw material of the whole project: every important action
-- (login, logout, order, forbidden access) becomes one row here. The Detection
-- Engine (Phase 6) reads these rows and decides whether they form an attack.
--
-- It is deliberately append-only: events are never updated, only inserted.
-- =============================================================================

CREATE TABLE security_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    event_type    VARCHAR(60) NOT NULL,
    -- Optional hint from the collector ("this looked worth noticing"). The real
    -- decision is made by the rules in Phase 6, never by this column.
    severity_hint VARCHAR(20),
    source_ip     VARCHAR(45),                 -- IPv6 fits in 45 characters
    -- NULL is normal: a failed login for a non-existing account has no user_id.
    user_id       BIGINT REFERENCES users (id) ON DELETE SET NULL,
    -- The username as typed, kept even when user_id is NULL (forensics).
    username      VARCHAR(50),
    endpoint      VARCHAR(255),
    http_method   VARCHAR(10),
    status_code   INTEGER,
    user_agent    VARCHAR(512),
    description   TEXT,
    -- JSONB, not TEXT: the shape of "extra data" differs per event type
    -- (order_code, rule parameters, simulated attack name, ...). JSONB keeps it
    -- one column without losing the ability to query inside it (GIN index in V8).
    metadata      JSONB,
    -- Request correlation id (MDC): joins a security event to the application
    -- log lines of the same HTTP request.
    request_id    VARCHAR(36),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- The CHECK duplicates the Java enum SecurityEventType. That is the point:
    -- a typo like 'LOGIN_FAILED ' or 'LOGIN_FALED' cannot reach the database, so
    -- the detection rules can trust the data they read.
    -- Adding a new event type therefore requires a migration (V10, V11, ...).
    CONSTRAINT ck_security_events_type CHECK (event_type IN (
        'LOGIN_SUCCESS', 'LOGIN_FAILED', 'LOGOUT', 'USER_REGISTERED',
        'PASSWORD_CHANGED', 'ACCESS_DENIED', 'ADMIN_ACCESS',
        'PRODUCT_CREATED', 'PRODUCT_UPDATED', 'PRODUCT_DELETED',
        'ORDER_CREATED', 'ORDER_CANCELLED', 'ORDER_STATUS_CHANGED',
        'API_REQUEST', 'SUSPICIOUS_REQUEST', 'SIMULATION_RUN')),
    CONSTRAINT ck_security_events_severity
        CHECK (severity_hint IS NULL OR severity_hint IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_security_events_status_code
        CHECK (status_code IS NULL OR status_code BETWEEN 100 AND 599),
    CONSTRAINT ck_security_events_http_method
        CHECK (http_method IS NULL OR http_method IN ('GET', 'POST', 'PUT', 'PATCH', 'DELETE', 'HEAD', 'OPTIONS'))
);

-- Index strategy: an SOC query is almost always "filter by something + newest
-- first". Each index therefore ends with occurred_at DESC.
CREATE INDEX idx_security_events_occurred_at      ON security_events (occurred_at DESC);
CREATE INDEX idx_security_events_ip_time          ON security_events (source_ip, occurred_at DESC);
CREATE INDEX idx_security_events_type_time        ON security_events (event_type, occurred_at DESC);
CREATE INDEX idx_security_events_user_time        ON security_events (user_id, occurred_at DESC);
CREATE INDEX idx_security_events_username_time    ON security_events (username, occurred_at DESC);

-- The multi-column index that answers "what did this IP do, by event type,
-- in the last minute" - the BruteForce / RequestFlood question in Phase 6.
CREATE INDEX idx_security_events_ip_type_time     ON security_events (source_ip, event_type, occurred_at DESC);

-- Join key back to the application log of the same request.
CREATE INDEX idx_security_events_request_id       ON security_events (request_id);
