-- =============================================================================
-- V2 : CATALOG  (categories, products)
-- =============================================================================

-- -----------------------------------------------------------------------------
-- categories : product grouping. Deactivated with "active = false" instead of
-- being deleted, so that product history stays meaningful.
-- -----------------------------------------------------------------------------
CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL,
    -- slug = URL friendly identifier used by /products?category=electronics
    slug        VARCHAR(120) NOT NULL,
    description VARCHAR(500),
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_categories_name UNIQUE (name),
    CONSTRAINT uk_categories_slug UNIQUE (slug),
    CONSTRAINT ck_categories_slug_format CHECK (slug ~ '^[a-z0-9-]{2,120}$')
);

-- -----------------------------------------------------------------------------
-- products
-- -----------------------------------------------------------------------------
CREATE TABLE products (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- NULL allowed + SET NULL on delete: removing a category must not delete
    -- products (the shop would lose sellable items). Phase 4 prefers setting
    -- categories.active = false, hard deletion is the exception.
    category_id BIGINT REFERENCES categories (id) ON DELETE SET NULL,
    name        VARCHAR(150)  NOT NULL,
    slug        VARCHAR(170)  NOT NULL,
    description TEXT,
    price       NUMERIC(12,2) NOT NULL,
    stock       INTEGER       NOT NULL DEFAULT 0,
    image_url   VARCHAR(255),
    status      VARCHAR(20)   NOT NULL DEFAULT 'ACTIVE',
    -- Optimistic locking (see VersionedEntity in Java). Hibernate compares this
    -- value on update, so two customers cannot buy the same last item without
    -- one of them receiving an error instead of a negative stock.
    version     BIGINT        NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uk_products_slug   UNIQUE (slug),
    CONSTRAINT ck_products_price  CHECK (price >= 0),
    -- The double safety net for overselling: the service checks the stock, and
    -- the database refuses to store a negative value even if the code fails.
    CONSTRAINT ck_products_stock  CHECK (stock >= 0),
    CONSTRAINT ck_products_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'DISCONTINUED')),
    CONSTRAINT ck_products_slug_format CHECK (slug ~ '^[a-z0-9-]{2,170}$')
);

CREATE INDEX idx_products_category ON products (category_id);
CREATE INDEX idx_products_status   ON products (status);
-- Case-insensitive product search (Phase 4) without a full text index: the
-- functional index matches the "lower(name) LIKE lower(:keyword)" query shape.
CREATE INDEX idx_products_name_lower ON products (lower(name));
