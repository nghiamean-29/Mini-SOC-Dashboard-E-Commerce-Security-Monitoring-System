-- =============================================================================
-- V7 : SECURITY INCIDENTS  (security_incidents, incident_alerts, incident_notes)
-- -----------------------------------------------------------------------------
-- One alert = one suspicion. One incident = one investigation.
-- Correlation merges related alerts (same source, close in time) into a single
-- incident, which is what a SOC analyst actually works on.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- incident_code_seq : the human readable incident number (INC-0001).
-- -----------------------------------------------------------------------------
-- Same reasoning as order_code_seq in V4: a sequence gives a unique number
-- before the insert (no read-then-write race, no retry), and the accepted
-- trade-off is that a failed transaction leaves a gap. An incident code is
-- quoted in reports and in conversations ("look at INC-0007"), so it must be
-- short, stable and unique - never reused.
CREATE SEQUENCE incident_code_seq START WITH 1 INCREMENT BY 1;

CREATE TABLE security_incidents (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Human readable code (INC-0001) used in the dashboard, in reports and in
    -- conversations ("look at INC-0007"). Number from incident_code_seq.
    incident_code VARCHAR(20)  NOT NULL,
    title         VARCHAR(200) NOT NULL,
    incident_type VARCHAR(50)  NOT NULL,
    severity      VARCHAR(20)  NOT NULL,
    source_ip     VARCHAR(45),
    status        VARCHAR(20)  NOT NULL DEFAULT 'OPEN',
    -- The analyst who owns the investigation. SET NULL keeps the incident if the
    -- account is removed; reassignment is a normal workflow operation.
    assigned_to   BIGINT REFERENCES users (id) ON DELETE SET NULL,
    -- Denormalised counter for the dashboard list (NFR-PERF-01).
    alert_count   INTEGER      NOT NULL DEFAULT 0,
    description   TEXT,
    resolution    TEXT,
    detected_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    resolved_at   TIMESTAMPTZ,
    version       BIGINT       NOT NULL DEFAULT 0,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uk_security_incidents_code UNIQUE (incident_code),
    CONSTRAINT ck_security_incidents_type CHECK (incident_type IN (
        'POSSIBLE_BRUTE_FORCE_ATTACK', 'POSSIBLE_REQUEST_FLOOD', 'POSSIBLE_SQL_INJECTION',
        'POSSIBLE_UNAUTHORIZED_ACCESS', 'SUSPECTED_ACCOUNT_TAKEOVER',
        'MIXED_SUSPICIOUS_ACTIVITY')),
    CONSTRAINT ck_security_incidents_severity
        CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_security_incidents_status
        CHECK (status IN ('OPEN', 'INVESTIGATING', 'RESOLVED', 'FALSE_POSITIVE')),
    CONSTRAINT ck_security_incidents_alert_count CHECK (alert_count >= 0),
    -- An incident cannot be closed without recording when it was closed.
    CONSTRAINT ck_security_incidents_resolved
        CHECK ((status IN ('RESOLVED', 'FALSE_POSITIVE') AND resolved_at IS NOT NULL)
            OR (status NOT IN ('RESOLVED', 'FALSE_POSITIVE')))
);

CREATE INDEX idx_security_incidents_status    ON security_incidents (status, detected_at DESC);
CREATE INDEX idx_security_incidents_severity  ON security_incidents (severity, detected_at DESC);
CREATE INDEX idx_security_incidents_ip_time   ON security_incidents (source_ip, detected_at DESC);
CREATE INDEX idx_security_incidents_assigned  ON security_incidents (assigned_to);

-- -----------------------------------------------------------------------------
-- incident_alerts : pure join table -> @ManyToMany in Java.
-- PRIMARY KEY (incident_id, alert_id) is the idempotency guarantee chosen in
-- Phase 0 (DB-8): the correlation service may run twice, the database will not
-- create a duplicate link.
-- -----------------------------------------------------------------------------
CREATE TABLE incident_alerts (
    incident_id BIGINT NOT NULL REFERENCES security_incidents (id) ON DELETE CASCADE,
    alert_id    BIGINT NOT NULL REFERENCES security_alerts (id) ON DELETE CASCADE,
    PRIMARY KEY (incident_id, alert_id)
);

-- "Which incident does this alert belong to?" (alert detail page)
CREATE INDEX idx_incident_alerts_alert_id ON incident_alerts (alert_id);

-- -----------------------------------------------------------------------------
-- incident_notes : the investigation notebook (FR-INC-05).
-- Append-only: a note is evidence of the analyst's reasoning, it is never edited.
-- -----------------------------------------------------------------------------
CREATE TABLE incident_notes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id     BIGINT      NOT NULL REFERENCES security_incidents (id) ON DELETE CASCADE,
    author_id       BIGINT REFERENCES users (id) ON DELETE SET NULL,
    -- Denormalised, same reason as audit_logs: the note must stay readable even
    -- if the account is later removed.
    author_username VARCHAR(50),
    content         TEXT        NOT NULL,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_incident_notes_content CHECK (length(trim(content)) > 0)
);

CREATE INDEX idx_incident_notes_incident ON incident_notes (incident_id, created_at);
