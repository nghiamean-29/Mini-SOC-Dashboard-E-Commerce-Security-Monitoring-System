-- =============================================================================
-- V4 : ORDERS  (orders, order_items)
-- -----------------------------------------------------------------------------
-- Money rule: the ORDER owns its numbers. Prices are copied into order_items at
-- checkout time, so changing a product price later can never rewrite history.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- order_code_seq : the source of the human readable order number.
-- -----------------------------------------------------------------------------
-- Why a sequence and not COUNT(*) + 1, and not "format the id after insert"?
--
--   * COUNT(*) + 1 collides: two simultaneous checkouts read the same count and
--     both produce ORD-20260921-0007. The UNIQUE constraint would reject one of
--     them - a customer seeing an error because somebody else was shopping at
--     the same moment.
--   * Formatting the primary key after the insert requires a(n) INSERT + UPDATE
--     pair (order_code is NOT NULL), i.e. two statements to write one fact.
--   * nextval() never returns the same number twice, so the code is unique
--     BEFORE the insert - one statement, no retry logic, and the number is
--     already known when the confirmation page is rendered.
--
-- Accepted trade-off (documented, not hidden): a failed transaction consumes
-- the number, so order codes have gaps. Gap-free numbering would require
-- locking the whole table for every checkout - a high price for cosmetics.
-- The sequence is owned by no column on purpose: order_code is a business
-- identifier composed by the application, not a serial column.
CREATE SEQUENCE order_code_seq START WITH 1 INCREMENT BY 1;

-- -----------------------------------------------------------------------------
-- orders
-- -----------------------------------------------------------------------------
CREATE TABLE orders (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Human readable code (ORD-20260921-000042) shown to the customer and used
    -- in URLs. Number from order_code_seq, date part from the application clock
    -- (see com.yak.minisoc.util.BusinessCodes).
    order_code       VARCHAR(30) NOT NULL,
    user_id          BIGINT      NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    -- RESTRICT on purpose: an order is a financial record, it must not disappear
    -- because somebody deleted the customer row. Users are deactivated instead.
    status           VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    total_amount     NUMERIC(12,2) NOT NULL DEFAULT 0,
    shipping_name    VARCHAR(120),
    shipping_phone   VARCHAR(20),
    shipping_address VARCHAR(255),
    note             VARCHAR(500),
    version          BIGINT      NOT NULL DEFAULT 0,
    cancelled_at     TIMESTAMPTZ,
    cancel_reason    VARCHAR(255),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_orders_code   UNIQUE (order_code),
    -- The six states from the specification (SDD section 4.2). The legal
    -- transitions between them live in the Java enum OrderStatus.
    CONSTRAINT ck_orders_status CHECK (status IN ('PENDING', 'CONFIRMED', 'PROCESSING',
                                                  'SHIPPED', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_orders_total  CHECK (total_amount >= 0),
    -- A cancelled order must say when it was cancelled: an order cannot be
    -- "cancelled" without that fact being recorded.
    CONSTRAINT ck_orders_cancelled
        CHECK ((status = 'CANCELLED' AND cancelled_at IS NOT NULL)
            OR (status <> 'CANCELLED'))
);

CREATE INDEX idx_orders_user_time  ON orders (user_id, created_at DESC);
CREATE INDEX idx_orders_status     ON orders (status);
CREATE INDEX idx_orders_created_at ON orders (created_at DESC);

-- -----------------------------------------------------------------------------
-- order_items : snapshot lines (product name + unit price frozen at checkout)
-- -----------------------------------------------------------------------------
CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT      NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
    -- SET NULL and not CASCADE: if a product is ever hard-deleted, the order line
    -- must survive (it is history). The snapshot columns below keep it readable.
    product_id   BIGINT      REFERENCES products (id) ON DELETE SET NULL,
    product_name VARCHAR(150) NOT NULL,          -- snapshot
    unit_price   NUMERIC(12,2) NOT NULL,         -- snapshot
    quantity     INTEGER     NOT NULL,
    -- Stored instead of being recomputed: the invoice total must be auditable
    -- even if a rounding rule changes later.
    line_total   NUMERIC(12,2) NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_order_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_order_items_price    CHECK (unit_price >= 0),
    CONSTRAINT ck_order_items_total    CHECK (line_total >= 0)
);

CREATE INDEX idx_order_items_order   ON order_items (order_id);
CREATE INDEX idx_order_items_product ON order_items (product_id);
