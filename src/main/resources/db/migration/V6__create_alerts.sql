-- =============================================================================
-- V6 : SECURITY ALERTS  (security_alerts, alert_events)
-- -----------------------------------------------------------------------------
-- An alert is a JUDGEMENT produced by a detection rule from one or more events.
-- Events are facts ("login failed"), alerts are conclusions ("this is a brute
-- force attack"). Keeping both separate is what makes the SOC explainable:
-- every alert can point back at the evidence that produced it.
-- =============================================================================

CREATE TABLE security_alerts (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_type          VARCHAR(50) NOT NULL,
    severity            VARCHAR(20) NOT NULL,
    source_ip           VARCHAR(45),
    user_id             BIGINT REFERENCES users (id) ON DELETE SET NULL,
    username            VARCHAR(50),
    description         TEXT,
    detected_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    status              VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    -- How many raw events contributed to this alert. Denormalised on purpose:
    -- the dashboard shows it on every row (NFR-PERF-01), and counting the linked
    -- events each time would be an extra query per alert.
    related_event_count INTEGER     NOT NULL DEFAULT 1,
    -- Duplicate suppression key: alert_type + source_ip + time bucket.
    -- Phase 7 does not create a second alert while one with the same key exists
    -- (cooldown, decision D-5). UNIQUE makes that guarantee a database rule, so
    -- two threads racing cannot both insert "the first alert".
    dedup_key           VARCHAR(150) NOT NULL,
    -- Which rule produced the alert (audit + rule tuning: a rule that fires
    -- constantly is a rule that needs adjusting, or a false-positive factory).
    rule_name           VARCHAR(50),
    version             BIGINT      NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),

    CONSTRAINT uk_security_alerts_dedup UNIQUE (dedup_key),
    -- Mirrors the Java enums AlertType / Severity / AlertStatus (see V5 for the
    -- reasoning). A new alert type means a new migration.
    CONSTRAINT ck_security_alerts_type CHECK (alert_type IN (
        'BRUTE_FORCE', 'UNAUTHORIZED_ACCESS', 'REQUEST_FLOOD',
        'SQL_INJECTION', 'SUSPICIOUS_ACCOUNT_ACTIVITY')),
    CONSTRAINT ck_security_alerts_severity
        CHECK (severity IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    CONSTRAINT ck_security_alerts_status
        CHECK (status IN ('OPEN', 'INVESTIGATING', 'RESOLVED', 'FALSE_POSITIVE')),
    -- At least one event produced the alert; and the cooldown can only ever
    -- increase the counter, so it starts at 1.
    CONSTRAINT ck_security_alerts_related_events CHECK (related_event_count > 0)
);

CREATE INDEX idx_security_alerts_detected_at ON security_alerts (detected_at DESC);
CREATE INDEX idx_security_alerts_status      ON security_alerts (status, detected_at DESC);
CREATE INDEX idx_security_alerts_severity    ON security_alerts (severity, detected_at DESC);
CREATE INDEX idx_security_alerts_type        ON security_alerts (alert_type, detected_at DESC);
CREATE INDEX idx_security_alerts_ip_time     ON security_alerts (source_ip, detected_at DESC);

-- -----------------------------------------------------------------------------
-- alert_events : the evidence. Which security events led to this alert?
-- Pure join table (no extra columns) -> @ManyToMany in Java.
-- -----------------------------------------------------------------------------
CREATE TABLE alert_events (
    alert_id BIGINT NOT NULL REFERENCES security_alerts (id) ON DELETE CASCADE,
    -- CASCADE: if the retention job purges old events, the link row is
    -- meaningless and must disappear with them. The alert itself stays.
    event_id BIGINT NOT NULL REFERENCES security_events (id) ON DELETE CASCADE,
    PRIMARY KEY (alert_id, event_id)
);

-- Reverse question: "has this event already been used as evidence?"
CREATE INDEX idx_alert_events_event_id ON alert_events (event_id);
