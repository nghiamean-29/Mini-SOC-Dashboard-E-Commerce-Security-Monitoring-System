-- =============================================================================
-- V3 : CART  (carts, cart_items)
-- =============================================================================

-- -----------------------------------------------------------------------------
-- carts : exactly one cart per customer (UNIQUE user_id enforces it in the
-- database, so a race condition cannot create a second cart).
-- -----------------------------------------------------------------------------
CREATE TABLE carts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_carts_user UNIQUE (user_id)
);

-- -----------------------------------------------------------------------------
-- cart_items
-- -----------------------------------------------------------------------------
CREATE TABLE cart_items (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cart_id    BIGINT      NOT NULL REFERENCES carts (id) ON DELETE CASCADE,
    product_id BIGINT      NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    quantity   INTEGER     NOT NULL,
    -- Price snapshot at the moment the item was added. The cart then shows the
    -- price the customer actually saw; Phase 4 re-checks it at checkout and warns
    -- if the product price changed in the meantime.
    unit_price NUMERIC(12,2) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Adding the same product twice must UPDATE the existing line, never create
    -- a second one. The database guarantees it; the service simply does an upsert.
    CONSTRAINT uk_cart_items_cart_product UNIQUE (cart_id, product_id),
    CONSTRAINT ck_cart_items_quantity     CHECK (quantity > 0 AND quantity <= 999),
    CONSTRAINT ck_cart_items_price        CHECK (unit_price >= 0)
);

CREATE INDEX idx_cart_items_product ON cart_items (product_id);
