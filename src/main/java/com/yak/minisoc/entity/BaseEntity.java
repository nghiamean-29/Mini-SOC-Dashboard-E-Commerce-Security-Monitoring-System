package com.yak.minisoc.entity;

import jakarta.persistence.Column;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.MappedSuperclass;
import java.io.Serializable;
import java.time.Instant;
import org.hibernate.Hibernate;
import org.hibernate.annotations.CreationTimestamp;
import org.hibernate.annotations.UpdateTimestamp;

/**
 * Shared superclass for every <strong>mutable</strong> entity of the project.
 *
 * <p><strong>Why a superclass at all?</strong> Every one of our tables carries the same
 * three technical columns, and they must be declared exactly once so that no entity can
 * forget them. {@code @MappedSuperclass} means: "these fields are mapped, but this class
 * is not a table of its own" - each concrete entity inherits the columns into its own
 * table. ({@code @Entity} on an abstract class would create a table for the parent, which
 * we explicitly do not want.)</p>
 *
 * <p><strong>The three columns:</strong></p>
 * <ul>
 *   <li>{@code id} - surrogate primary key, generated by the database
 *       ({@code GENERATED BY DEFAULT AS IDENTITY} in SQL, {@code IDENTITY} here).</li>
 *   <li>{@code created_at} - technical "row was inserted" timestamp, filled by Hibernate
 *       ({@link CreationTimestamp}) and never updated ({@code updatable = false}).</li>
 *   <li>{@code updated_at} - technical "row was last modified" timestamp
 *       ({@link UpdateTimestamp}).</li>
 * </ul>
 *
 * <p><strong>Technical timestamps vs business timestamps:</strong> {@code created_at} is
 * bookkeeping. Tables that describe something that <em>happened</em> add their own
 * business timestamp ({@code occurred_at}, {@code detected_at}, {@code resolved_at})
 * which the application sets explicitly, because the application - not Hibernate - knows
 * when the event really took place (for example when the HTTP request arrived).</p>
 *
 * <p><strong>Why {@link Instant} and not {@link java.time.LocalDateTime}:</strong>
 * {@code Instant} is an absolute point on the timeline and maps to PostgreSQL
 * {@code TIMESTAMPTZ}, so every timestamp is stored in UTC (NFR-DATA-01). Converting to
 * {@code Asia/Ho_Chi_Minh} happens only when the value is formatted for the screen.</p>
 *
 * <h3>equals / hashCode - the part that JPA beginners get wrong</h3>
 *
 * <p>Entities are used inside {@code HashSet}s and {@code HashMap}s (for example
 * {@code Set<Role> roles} on {@code User}). A collection like that silently breaks when
 * {@code hashCode()} changes while the object is inside it, so the two methods must obey
 * these rules:</p>
 * <ul>
 *   <li><strong>hashCode is constant per class</strong> ({@code getClass().hashCode()}).
 *       It never changes, not even when the id is assigned on insert - so an entity stays
 *       findable in its hashed bucket.</li>
 *   <li><strong>equals compares the id</strong>, and only for objects of exactly the same
 *       Hibernate entity class ({@link Hibernate#getClass(Object)} resolves proxies, so a
 *       lazy proxy and its target compare equal).</li>
 *   <li><strong>A transient entity (id == null) equals nothing</strong>, not even itself.
 *       Two "not yet saved" objects are therefore not deduplicated by the collection;
 *       duplicates are prevented where they really matter - by UNIQUE constraints in the
 *       database.</li>
 *   <li>Both methods are {@code final}: a subclass must not change the identity contract,
 *       otherwise {@code Set} semantics differ per subclass.</li>
 * </ul>
 */
@MappedSuperclass
public abstract class BaseEntity implements Serializable {

    private static final long serialVersionUID = 1L;

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id", nullable = false, updatable = false)
    private Long id;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    @UpdateTimestamp
    @Column(name = "updated_at", nullable = false)
    private Instant updatedAt;

    public Long getId() {
        return id;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    /**
     * True when the entity exists in the database (has an assigned id).
     * Useful in services and tests to express intent: {@code if (user.isNew())}.
     */
    public boolean isNew() {
        return id == null;
    }

    @Override
    public final boolean equals(Object other) {
        if (this == other) {
            return true;
        }
        if (other == null || Hibernate.getClass(this) != Hibernate.getClass(other)) {
            return false;
        }
        BaseEntity that = (BaseEntity) other;
        return id != null && id.equals(that.id);
    }

    @Override
    public final int hashCode() {
        // Constant per class on purpose: stable for the whole lifetime of the object.
        return getClass().hashCode();
    }

    /**
     * Deliberately short: a full field dump would pull lazy associations into log files
     * (and into the database) and could print personal data. Log the id, query the rest
     * explicitly when it is actually needed.
     */
    @Override
    public String toString() {
        return getClass().getSimpleName() + "{id=" + id + "}";
    }
}
