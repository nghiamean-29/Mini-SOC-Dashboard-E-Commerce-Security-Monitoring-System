package com.yak.minisoc.security;

import static org.assertj.core.api.Assertions.assertThat;

import com.yak.minisoc.entity.BaseEntity;
import com.yak.minisoc.entity.Role;
import com.yak.minisoc.entity.User;
import com.yak.minisoc.entity.UserStatus;
import java.lang.reflect.Field;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.authority.SimpleGrantedAuthority;

/**
 * Unit tests for {@link AuthenticatedUser} - the object that represents "who is logged in".
 *
 * <p>No Spring, no database: the principal is built from a plain {@code User} entity. That
 * is only possible because the entity and this class have no framework dependencies on
 * their construction path, which is a design property worth keeping.</p>
 *
 * <p>Three of these tests describe real security behaviour, not bookkeeping:</p>
 * <ul>
 *   <li>role codes become {@code ROLE_}-prefixed authorities (the {@code hasRole} contract);</li>
 *   <li>a LOCKED or DISABLED account reports itself as unusable, which is what makes Spring
 *       Security refuse the login before any controller runs;</li>
 *   <li>{@code toString()} never contains the password hash.</li>
 * </ul>
 */
class AuthenticatedUserTest {

    private static User user(String username, UserStatus status, String... roleCodes) {
        User user = User.create(username, username + "@example.com", "$2a$12$storedHashValue", "Test User");
        for (String code : roleCodes) {
            user.addRole(Role.create(code, code, null));
        }
        if (status == UserStatus.LOCKED) {
            user.lock();
        } else if (status == UserStatus.DISABLED) {
            user.disable();
        }
        return user;
    }

    /**
     * Gives an unsaved entity an id.
     *
     * <p>The id is generated by the database (IDENTITY), so it is normally {@code null}
     * until the entity is persisted. Reflection is the honest way to test what the
     * principal does with a real id without starting a database - and it fails loudly
     * (instead of silently passing) if the field is ever renamed.</p>
     */
    private static User withId(User user, long id) {
        try {
            Field field = BaseEntity.class.getDeclaredField("id");
            field.setAccessible(true);
            field.set(user, id);
            return user;
        } catch (ReflectiveOperationException e) {
            throw new IllegalStateException("BaseEntity.id is no longer reflectively reachable", e);
        }
    }

    @Test
    @DisplayName("role codes become ROLE_-prefixed authorities (what hasRole() checks)")
    void roleCodesBecomeAuthorities() {
        AuthenticatedUser principal = AuthenticatedUser.from(
                user("analyst", UserStatus.ACTIVE, AppRoles.SOC_ANALYST, AppRoles.ADMIN));

        assertThat(principal.getAuthorities())
                .extracting(GrantedAuthority::getAuthority)
                .containsExactly("ROLE_SOC_ANALYST", "ROLE_ADMIN");
        assertThat(principal.hasRole(AppRoles.SOC_ANALYST)).isTrue();
        assertThat(principal.hasRole(AppRoles.CUSTOMER)).isFalse();
    }

    @Test
    @DisplayName("a user without roles has no authorities at all (fail closed)")
    void userWithoutRolesHasNoAuthorities() {
        AuthenticatedUser principal = AuthenticatedUser.from(user("nobody", UserStatus.ACTIVE));

        assertThat(principal.getAuthorities()).isEmpty();
        // A logged-in user without authorities can still open the pages that only require
        // authentication - and nothing else. That is the intended behaviour.
        assertThat(principal.isEnabled()).isTrue();
    }

    @Test
    @DisplayName("the database id travels with the principal (the reason this class exists)")
    void carriesTheDatabaseId() {
        AuthenticatedUser principal = AuthenticatedUser.from(
                withId(user("alice", UserStatus.ACTIVE, AppRoles.CUSTOMER), 42L));

        // Phase 4+ reads this id to answer "which orders are mine?" without a second
        // query by username.
        assertThat(principal.getUserId()).isEqualTo(42L);
    }

    @Test
    @DisplayName("ACTIVE account: usable in every sense")
    void activeAccountIsUsable() {
        AuthenticatedUser principal = AuthenticatedUser.from(
                withId(user("alice", UserStatus.ACTIVE, AppRoles.CUSTOMER), 7L));

        assertThat(principal.getUserId()).isEqualTo(7L);
        assertThat(principal.isEnabled()).isTrue();
        assertThat(principal.isAccountNonLocked()).isTrue();
        assertThat(principal.isAccountNonExpired()).isTrue();
        assertThat(principal.isCredentialsNonExpired()).isTrue();
        assertThat(principal.getStatus()).isEqualTo(UserStatus.ACTIVE);
    }

    @Test
    @DisplayName("LOCKED account: Spring Security refuses the login (isAccountNonLocked = false)")
    void lockedAccountIsRefused() {
        AuthenticatedUser principal = AuthenticatedUser.from(
                user("locked", UserStatus.LOCKED, AppRoles.CUSTOMER));

        assertThat(principal.isAccountNonLocked()).isFalse();
        // Still enabled: "locked" and "disabled" are different situations, and the login
        // error message is deliberately the same for both.
        assertThat(principal.isEnabled()).isTrue();
    }

    @Test
    @DisplayName("DISABLED account: Spring Security refuses the login (isEnabled = false)")
    void disabledAccountIsRefused() {
        AuthenticatedUser principal = AuthenticatedUser.from(
                user("disabled", UserStatus.DISABLED, AppRoles.CUSTOMER));

        assertThat(principal.isEnabled()).isFalse();
        assertThat(principal.isAccountNonLocked()).isTrue();
    }

    @Test
    @DisplayName("the password hash is available to the authentication provider")
    void exposesTheStoredHash() {
        AuthenticatedUser principal = AuthenticatedUser.from(user("alice", UserStatus.ACTIVE, AppRoles.CUSTOMER));

        // DaoAuthenticationProvider calls getPassword() to compare with the submitted
        // password; the hash itself must never leave the server.
        assertThat(principal.getPassword()).isEqualTo("$2a$12$storedHashValue");
    }

    @Test
    @DisplayName("toString() never prints the password hash")
    void toStringDoesNotLeakTheHash() {
        AuthenticatedUser principal = AuthenticatedUser.from(
                user("alice", UserStatus.ACTIVE, AppRoles.CUSTOMER));

        assertThat(principal.toString())
                .contains("alice")
                .contains("ROLE_CUSTOMER")
                .doesNotContain("$2a$12$storedHashValue");
    }

    @Test
    @DisplayName("two principals are equal when they are the same account id")
    void equalityIsBasedOnTheUserId() {
        AuthenticatedUser first = AuthenticatedUser.from(
                withId(user("alice", UserStatus.ACTIVE, AppRoles.CUSTOMER), 7L));
        // Same id, different object and even different username: still the same account.
        AuthenticatedUser sameAccount = AuthenticatedUser.from(
                withId(user("alice-renamed", UserStatus.ACTIVE, AppRoles.ADMIN), 7L));
        AuthenticatedUser otherAccount = AuthenticatedUser.from(
                withId(user("bob", UserStatus.ACTIVE, AppRoles.CUSTOMER), 8L));

        assertThat(first).isEqualTo(sameAccount).hasSameHashCodeAs(sameAccount);
        assertThat(first).isNotEqualTo(otherAccount);
        // Not equal to a Spring Security User with the same name: they are different
        // concepts (one has an id, the other does not).
        assertThat(first).isNotEqualTo(new SimpleGrantedAuthority("ROLE_CUSTOMER"));
    }

    @Test
    @DisplayName("AppRoles.authority() adds the prefix exactly once")
    void authorityPrefixIsIdempotent() {
        assertThat(AppRoles.authority(AppRoles.ADMIN)).isEqualTo("ROLE_ADMIN");
        assertThat(AppRoles.authority("ROLE_ADMIN")).isEqualTo("ROLE_ADMIN");
        assertThat(AppRoles.isKnown(AppRoles.SOC_ANALYST)).isTrue();
        assertThat(AppRoles.isKnown("SUPERUSER")).isFalse();
        assertThat(AppRoles.ALL).containsExactly("CUSTOMER", "ADMIN", "SOC_ANALYST");
    }
}
